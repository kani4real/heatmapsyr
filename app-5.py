# 2. AI-Аналитика функциясы (Ғылыми жоба негізінде)
# ---------------------------------------------------------------
def generate_ai_analysis(year, subset):
    analysis = f"#### 🤖 {year} жылға арналған AI-талдау нәтижелері\n\n"

    # 1. Кезең сипаттамасы (тарихи оқиғаларға байланысты)
    if year < 1853:
        analysis += "**📌 Тарихи кезең:** Бұл Сырдың төменгі ағысында Ресей империясының әскери-отарлау экспансиясының алғашқы кезеңі. 1847 жылы Райым бекінісінің салынуы өңірдегі дәстүрлі көші-қон жолдарының өзгеруіне түрткі болды.\n\n"
    elif 1853 <= year < 1867:
        analysis += "**📌 Тарихи кезең:** Бекіністер желісінің оңтүстікке қарай ішкерілеу кезеңі. Ақмешіттің (1853 ж.) құлауымен Сырдария әскери желісі толық қалыптасты. Бұл кезеңнің басты ерекшелігі — Жанқожа Нұрмұхамедұлы (1853-1858 жж.) мен Есет Көтібарұлы (1855 ж.) бастаған ұлт-азаттық көтерілістер. Олардың нәтижесінде бекіністер маңындағы бақылау күшейіп, мыңдаған қазақ отбасылары күштеп қоныс аударуға мәжбүр болды.\n\n"
    else:
        analysis += "**📌 Тарихи кезең:** Әкімшілік рәсімделу және тұрақты отарлық қоныстану кезеңі. 1867 жылғы «Ережеге» сәйкес Қазалы мен Перовск уездері құрылып, бекіністер айналасында суармалы егіншілікке негізделген жартылай отырықшы ауылдардың көбеюі байқалады.\n\n"

    # 2. Демографиялық және салыстырмалы талдау
    fort_count = len(subset)
    analysis += f"**📊 Географиялық таралу:** Осы жылға қарай картада {fort_count} негізгі қоныстану/әкімшілік ошағы тіркелді. Қоныстанудың негізгі заңдылығы — су ресурстарына (Сырдария арнасына) және жаңа әскери бекіністерге тікелей тәуелділік.\n\n"

    if year == 1897:
        analysis += "**📈 1897 жылғы санақ негізіндегі демографиялық талдау:** Бүкілресейлік халық санағының мәліметі бойынша, Қазалы уезінде қазақтардың үлесі **96,6%**, ал Перовск уезінде **97,4%** құрады. Салыстырмалы түрде алғанда (мысалы, Әулиеата уезімен — 90,8%), Сырдың төменгі ағысы дәстүрлі қазақ шаруашылығының басты тірек аймағы болып қалғанын көрсетеді. Бұл өңірде көшпелі мал шаруашылығы мен өзен жағалауындағы егіншілік қатар дамыды.\n\n"

    return analysis


def fmt(n):
    """Санды 1 234 567 түрінде көрсету."""
    return f"{int(n):,}".replace(",", " ")


def pct(v):
    """Пайызды қазақша жазу: 61,0%."""
    return f"{v:.1f}%".replace(".", ",")


def src_links(ids):
    """[27], [30] сияқты дереккөз сілтемелерін markdown түрінде қайтарады."""
    return ", ".join(f"[[{i}]]({SOURCES_20[i][1]})" for i in ids)


def map_figure(func_new, func_old, **kwargs):
    """Plotly-дің жаңа (map) және ескі (mapbox) нұсқаларымен жұмыс істеу."""
    try:
        return getattr(px, func_new)(map_style="open-street-map", **kwargs)
    except AttributeError:
        return getattr(px, func_old)(mapbox_style="open-street-map", **kwargs)


