    census_view["kazakhs"] = census_view["kazakhs"].map(lambda v: fmt(v) if pd.notna(v) else "дерек жоқ")
    census_view["kazakh_share"] = census_view["kazakh_share"].map(lambda v: pct(v) if pd.notna(v) else "дерек жоқ")
    st.dataframe(
        census_view.rename(columns={
            "year": "Жыл", "unit": "Аумақ", "total": "Барлық халық",
            "kazakhs": "Қазақтар", "kazakh_share": "Қазақтар, %",
            "src": "Дереккөз", "note": "Ескертпе"}),
        use_container_width=True, hide_index=True,
    )

    # Ашаршылықтың демографиялық ізі (бүкіл КСРО бойынша)
    k26, k39 = USSR_KAZAKHS[1926], USSR_KAZAKHS[1939]
    st.info(
        f"**1926 → 1939: ашаршылықтың демографиялық ізі.** Бүкілодақтық санақтар "
        f"бойынша КСРО-дағы қазақтардың саны 1926 жылы {fmt(k26)} болса, 1939 жылы "
        f"{fmt(k39)} адамға дейін, яғни {fmt(k26 - k39)} адамға "
        f"({pct((k26 - k39) / k26 * 100)}) кеміді. {src_links([29])}"
    )

    # ---------------------------------------------------------------
    # 8. Ұлттық құрам
    # ---------------------------------------------------------------
    st.markdown("### 🧩 Қызылорда облысының ұлттық құрамы, 1939–1989")
    eth_long = ETHNIC_20.melt(id_vars=["year", "total"],
                              value_vars=ETHNIC_GROUPS + ["Басқалары"],
                              var_name="Ұлты", value_name="Адам саны")
    eth_long["Үлесі, %"] = (eth_long["Адам саны"] / eth_long["total"] * 100).round(1)
    fig_e = px.bar(
        eth_long, x=eth_long["year"].astype(str), y="Үлесі, %", color="Ұлты",
        text="Үлесі, %", hover_data={"Адам саны": True},
        color_discrete_sequence=["#e6550d", "#3182bd", "#756bb1", "#fdae6b", "#bdbdbd"],
        title="Ұлттық құрам (халықтың %)",
    )
    fig_e.update_traces(texttemplate="%{text:.1f}")
    fig_e.update_layout(barmode="stack", height=430, xaxis_title="Санақ жылы",
                        xaxis_type="category", separators=", ",
                        margin=dict(l=0, r=0, t=40, b=0), legend=dict(orientation="h", y=-0.2))
    st.plotly_chart(fig_e, use_container_width=True)
    st.caption(
        "1939 жылы облыс халқының 10,8%-ы — 1937 жылы Қиыр Шығыстан жер аударылған "
        f"корейлер. «Басқалары» — жалпы саннан көрсетілген төрт ұлтты шегергендегі айырма. "
        f"Дереккөздер: {src_links([30, 31, 32, 33, 34])}"
    )

    # ---------------------------------------------------------------
    # 9. Аудандар бойынша халық саны
    # ---------------------------------------------------------------
    st.markdown("### 🏘️ Аудандар бойынша халық саны, 1939–1979")
    dist_long = DISTRICTS_20.melt(id_vars="district", var_name="Жыл", value_name="Адам саны")
    dist_long["Жыл"] = dist_long["Жыл"].astype(str)
    fig_d = px.bar(
        dist_long, x="district", y="Адам саны", color="Жыл", barmode="group",
        color_discrete_sequence=["#fdd0a2", "#fd8d3c", "#d94801", "#7f2704"],
        title="Қызылорда облысының аудандары (санақтардың аудандық кестелері)",
    )
    fig_d.update_layout(height=450, xaxis_title="", margin=dict(l=0, r=0, t=40, b=0),
                        legend=dict(orientation="h", y=-0.3))
    st.plotly_chart(fig_d, use_container_width=True)
    st.caption(
        "Аудан атаулары қазақша берілген (санақта: Чиилийский, Яны-Курганский, "
        "Тереньузякский, Джалагашский т.б.). Жалағаш ауданы 1939 ж. санақта жоқ. "
        "1939 ж. Сырдария ауданының орталығы Қызылорда қаласында болған, 1958 жылдан — Тасбөгетте. "
        "Аудан шекаралары жылдар бойы өзгергендіктен, 1939–1959 жж. азаюдың себебін бұл "
        f"кесте өздігінен түсіндірмейді. Дереккөздер: {src_links([30, 31, 32, 33])}"
    )

    # ---------------------------------------------------------------
    # 10. Тарихи оқиғалар картасы және хронологиясы
    # ---------------------------------------------------------------
    st.markdown("### 🗺️ 20 ғасырдағы негізгі оқиғалар")
    chosen = st.multiselect("Кезеңдерді таңдаңыз", PERIODS_20, default=PERIODS_20)
    chosen_idx = [PERIODS_20.index(p) for p in chosen]
    events = [e for e in EVENTS_20 if e["period"] in chosen_idx]

    ev_map = pd.DataFrame([e for e in events if e["lat"] is not None])
    if not ev_map.empty:
        # Бір елді мекенге бір нүкте: сол жердегі барлық оқиғалар тізімі
        ev_map["label"] = ev_map["date"] + " — " + ev_map["title"]
        ev_map = (ev_map.groupby(["place", "lat", "lon"], as_index=False)
                  .agg(events=("label", "<br>".join), count=("label", "size")))
        fig_m = map_figure(
            "scatter_map", "scatter_mapbox",
            data_frame=ev_map, lat="lat", lon="lon", hover_name="place",
            hover_data={"events": True, "count": False, "lat": False, "lon": False},
            labels={"events": "Оқиғалар"},
            size="count", size_max=28, color_discrete_sequence=["#d94801"],
            center=dict(lat=45.6, lon=63.6), zoom=5.9,
            title="Оқиғалар болған жерлер (нүктенің үстіне апарып, тізімін көріңіз)",
        )
        fig_m.update_traces(marker=dict(sizemin=12, opacity=0.85))
        fig_m.update_layout(height=520, margin=dict(l=0, r=0, t=40, b=0), showlegend=False)
        st.plotly_chart(fig_m, use_container_width=True)
        st.caption(
            "Нүктелер — оқиға болған елді мекендердің қазіргі орны. Қарақұм "
            "көтерілісінің нүктесі шамамен (Қармақшы ауданы) көрсетілген. "
            "Нақты орны белгісіз оқиғалар картада емес, тек хронологияда берілген."
        )

    for period_i in chosen_idx:
        st.markdown(f"#### {PERIODS_20[period_i]}")
        for e in [e for e in events if e["period"] == period_i]:
            with st.expander(f"{e['date']} — {e['title']}"):
                st.write(e["text"])
                place = f"📍 {e['place']}. " if e["place"] else ""
                st.caption(f"{place}Дереккөз: {src_links(e['src'])}")

    # ---------------------------------------------------------------
    # 11. Дереккөздер
    # ---------------------------------------------------------------
    st.divider()
    with st.expander("📚 «20 ғасыр» бөлімінің дереккөздері"):
        for i, (title, url) in SOURCES_20.items():
            st.markdown(f"[{i}] {title}. URL: {url}")
    st.caption(
        "Ескерту: барлық сандар көрсетілген дереккөздерден өзгеріссіз алынды; "
        "пайыздар мен айырмалар осы сандардан бағдарлама арқылы есептелді. "
        "Ресми дереккөзі табылмаған көрсеткіштер (мысалы, Қызылорда өңіріндегі "
        "ашаршылық құрбандарының саны) әдейі көрсетілмеді."
    )
